function tokenColorFor(name, p) {
	const normalized = name.toLowerCase();
	const jsonLevel = normalized.match(/json key - level (\d)/);
	if (jsonLevel) {
		return [p.secondary, p.type, p.string, p.number, p.fg, p.primary, p.keyword, p.accent, p.success][Number(jsonLevel[1])];
	}
	if (normalized.includes("comment") || normalized.includes("blockquote") || normalized.includes("separator")) return p.comment;
	if (normalized.includes("invalid") || normalized.includes("deleted")) return p.error;
	if (normalized.includes("inserted")) return p.success;
	if (normalized.includes("changed")) return p.warning;
	if (normalized.includes("keyword") || normalized.includes("storage") || normalized.includes("decorator")) return p.keyword;
	if (normalized.includes("string link") || normalized.includes("link description")) return p.secondary;
	if (normalized.includes("string") || normalized.includes("symbol") || normalized.includes("raw block")) return p.string;
	if (normalized.includes("number") || normalized.includes("constant") || normalized.includes("link anchor")) return p.number;
	if (normalized.includes("function") || normalized.includes("method") || normalized.includes("sub-method")) return p.primary;
	if (normalized.includes("class") || normalized.includes("entity type") || normalized.includes("attribute")) return p.type;
	if (normalized.includes("operator") || normalized.includes("punctuation")) return p.accent;
	if (normalized.includes("regular expression") || normalized.includes("escape character")) return p.secondary;
	if (normalized.includes("heading") || normalized.includes("underline") || normalized.includes("url") || normalized.includes("link")) return p.primary;
	if (normalized.includes("italic") || normalized.includes("bold")) return p.secondary;
	if (normalized.includes("color")) return p.number;
	return p.fg;
}

function buildTokenColors(tokens, p) {
	return tokens.map((token) => ({
		...token,
		settings: {
			...token.settings,
			foreground: tokenColorFor(token.name || "", p)
		}
	}));
}

