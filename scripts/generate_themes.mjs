function tokenColorFor(name, p) {
	const normalized = name.toLowerCase();
	const jsonLevel = normalized.match(/json key - level (\d)/);
	if (jsonLevel) {
		return [p.secondary, p.type, p.string, p.number, p.fg, p.primary, p.keyword, p.accent, p.success][Number(jsonLevel[1])];
	}
	if (normalized.includes("comment") || normalized.includes("blockquote") || normalized.includes("separator")) return p.comment;
	if (normalized.includes("invalid") || normalized.includes("deleted")) return p.error;
	if (normalized.includes("inserted")) return p.success;
	if (normalized.includes("changed")) return p.warning;
	if (normalized.includes("keyword") || normalized.includes("storage") || normalized.includes("decorator")) return p.keyword;
	if (normalized.includes("string link") || normalized.includes("link description")) return p.secondary;
	if (normalized.includes("string") || normalized.includes("symbol") || normalized.includes("raw block")) return p.string;
	if (normalized.includes("number") || normalized.includes("constant") || normalized.includes("link anchor")) return p.number;
	if (normalized.includes("function") || normalized.includes("method") || normalized.includes("sub-method")) return p.primary;
	if (normalized.includes("class") || normalized.includes("entity type") || normalized.includes("attribute")) return p.type;
	if (normalized.includes("operator") || normalized.includes("punctuation")) return p.accent;
	if (normalized.includes("regular expression") || normalized.includes("escape character")) return p.secondary;
	if (normalized.includes("heading") || normalized.includes("underline") || normalized.includes("url") || normalized.includes("link")) return p.primary;
	if (normalized.includes("italic") || normalized.includes("bold")) return p.secondary;
	if (normalized.includes("color")) return p.number;
	return p.fg;
}

function buildTokenColors(tokens, p) {
	return tokens.map((token) => ({
		...token,
		settings: {
			...token.settings,
			foreground: tokenColorFor(token.name || "", p)
		}
	}));
}

function buildSemanticTokenColors(p) {
	return {
		"namespace": p.type,
		"type": p.type,
		"typeParameter": p.type,
		"class": p.type,
		"enum": p.type,
		"interface": p.type,
		"struct": p.type,
		"parameter": p.fg,
		"variable": p.fg,
		"variable.readonly": p.number,
		"property": p.fg,
		"enumMember": p.number,
		"event": p.secondary,
		"function": p.primary,
		"method": p.primary,
		"macro": p.keyword,
		"label": p.secondary,
		"comment": { "foreground": p.comment, "italic": true },
		"string": p.string,
		"number": p.number,
		"regexp": p.secondary,
		"operator": p.accent,
		"keyword": p.keyword,
		"decorator": p.keyword
	};
}

async function main() {
	const templateContent = await readFile(templatePath, "utf8");
	const template = JSON.parse(templateContent);

	for (const [key, palette] of Object.entries(palettes)) {
		// Deep clone
		const theme = JSON.parse(JSON.stringify(template));
		theme.name = palette.name;

		const colorMap = {
			"#0d0b1a": palette.bg,
			"#080712": palette.bgDark,
			"#1e1935": palette.bgActive,
			"#1e193c": palette.bgActive,
			"#141126": palette.bgInput,
			"#e0ddf5": palette.fg,
			"#a29fc2": palette.fgMuted,
			"#6c698f": palette.comment,
			"#433b70": palette.border,
			"#00ffd2": palette.primary,
			"#3cffdc": palette.primaryHover,
			"#cf9dff": palette.keyword,
			"#bfdbfe": palette.type,
			"#ff9de0": palette.error
		};

		// Helper to replace colors with mapping
		function mapColor(value) {
			if (typeof value !== "string") return value;
			const hex = value.toLowerCase();
			if (!hex.startsWith("#")) return value;

			// Look up 7-character prefix
			const prefix = hex.slice(0, 7);
			if (colorMap[prefix]) {
				const suffix = hex.slice(7); // Keep transparency/alpha suffix
				return colorMap[prefix] + suffix;
			}
			return value;
		}

		// Update colors block
		for (const [colorKey, colorVal] of Object.entries(theme.colors)) {
			theme.colors[colorKey] = mapColor(colorVal);
		}

		// Update tokenColors block
		for (const token of theme.tokenColors) {
			if (!token.settings || !token.settings.foreground) continue;

			const name = token.name || "";
			const fg = token.settings.foreground.toLowerCase();

			// Handle #ffffff strings & success-inserted block
			if (
				fg === "#ffffff" &&
				(name.includes("String, Symbols") ||
					name.includes("Inserted") ||
					name.includes("JSON Key - Level 2") ||
					name.includes("JSON Key - Level 8"))
			) {
				token.settings.foreground = palette.string;
				continue;
			}

			// Handle #ffffff defaults or others
			if (fg === "#ffffff") {
				continue;
			}

			// Map normal colors
			token.settings.foreground = mapColor(token.settings.foreground);
		}

		if (palette.fullWorkbench) {
			theme.colors = buildWorkbenchColors(palette);
			theme.tokenColors = buildTokenColors(template.tokenColors, palette);
			theme.semanticHighlighting = true;
			theme.semanticTokenColors = buildSemanticTokenColors(palette);
		}

		const outputPath = path.join(root, "themes", `${palette.fileName}-color-theme.json`);
		await writeFile(outputPath, JSON.stringify(theme, null, "\t") + "\n");
		console.log(`Generated ${outputPath}`);
	}
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
