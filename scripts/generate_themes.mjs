function channel(hex, i) {
	return parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16);
}

function blend(fg, bg) {
	const alpha = fg.length >= 9 ? parseInt(fg.slice(7, 9), 16) / 255 : 1;
	return [0, 1, 2].map((i) => channel(fg, i) * alpha + channel(bg, i) * (1 - alpha));
}

function luminance(rgb) {
	const [r, g, b] = rgb.map((v) => {
		const c = v / 255;
		return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
	});
	return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(fg, bg) {
	const base = [0, 1, 2].map((i) => channel(bg, i));
	const [hi, lo] = [luminance(blend(fg, bg)), luminance(base)].sort((a, b) => b - a);
	return (hi + 0.05) / (lo + 0.05);
}

// Readability gates every generated theme must pass (WCAG AA = 4.5:1 for text).
const contrastChecks = [
	["editor.foreground", "editor.background", 7],
	["editorLineNumber.foreground", "editor.background", 3],
	["tab.inactiveForeground", "tab.inactiveBackground", 4.5],
	["tab.activeForeground", "tab.activeBackground", 4.5],
	["sideBar.foreground", "sideBar.background", 7],
	["activityBar.inactiveForeground", "activityBar.background", 4.5],
	["statusBar.foreground", "statusBar.background", 7],
	["titleBar.inactiveForeground", "titleBar.inactiveBackground", 4.5],
	["button.foreground", "button.background", 4.5],
	["descriptionForeground", "editor.background", 4.5],
	["terminal.foreground", "terminal.background", 7],
	["terminal.ansiRed", "terminal.background", 4.5],
	["terminal.ansiGreen", "terminal.background", 4.5],
	["terminal.ansiYellow", "terminal.background", 4.5],
	["terminal.ansiBlue", "terminal.background", 4.5],
	["terminal.ansiMagenta", "terminal.background", 4.5],
	["terminal.ansiCyan", "terminal.background", 4.5],
	["terminal.ansiBrightBlack", "terminal.background", 4.5],
	["terminal.ansiBrightWhite", "terminal.background", 7]
];

function auditTheme(theme) {
	const failures = [];
	for (const [fgKey, bgKey, min] of contrastChecks) {
		const ratio = contrast(theme.colors[fgKey], theme.colors[bgKey]);
		if (ratio < min) failures.push(`${fgKey} on ${bgKey}: ${ratio.toFixed(2)} < ${min}`);
	}
	const bg = theme.colors["editor.background"];
	for (const token of theme.tokenColors) {
		const fg = token.settings?.foreground;
		if (!fg) continue;
		const min = 4.5;
		const ratio = contrast(fg, bg);
		if (ratio < min) failures.push(`token "${token.name}" ${fg}: ${ratio.toFixed(2)} < ${min}`);
	}
	return failures;
}

async function main() {
	const template = JSON.parse(await readFile(templatePath, "utf8"));
	const tokenTemplate = template.tokenColors;
	let failed = 0;

	for (const palette of Object.values(palettes)) {
		const theme = {
			name: palette.name,
			colors: buildWorkbenchColors(palette),
			tokenColors: buildTokenColors(tokenTemplate, palette),
			semanticHighlighting: true,
			semanticTokenColors: buildSemanticTokenColors(palette)
		};

		const failures = auditTheme(theme);
		if (failures.length) {
			failed += failures.length;
			console.error(`\n${palette.name} fails contrast checks:`);
			for (const failure of [...new Set(failures)]) console.error(`  - ${failure}`);
		}

		const outputPath = path.join(root, "themes", `${palette.fileName}-color-theme.json`);
		await writeFile(outputPath, JSON.stringify(theme, null, "\t") + "\n");
		console.log(`Generated ${outputPath}`);
	}

	if (failed) {
		console.error(`\n${failed} contrast failure(s). Adjust the palettes in scripts/palettes.mjs.`);
		process.exit(1);
	}
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
